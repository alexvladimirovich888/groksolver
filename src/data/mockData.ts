// Helper to format time relative to current moment
export const getRelativeTimeString = (minutesAgo: number = 0): string => {
  const d = new Date(Date.now() - minutesAgo * 60 * 1000);
  return d.toTimeString().split(' ')[0].substring(0, 5); // HH:MM
};

export const getFullTimeString = (secondsAgo: number = 0): string => {
  const d = new Date(Date.now() - secondsAgo * 1000);
  return d.toTimeString().split(' ')[0]; // HH:MM:SS
};

export const getFormattedCurrentDate = (): string => {
  const now = new Date();
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  const day = now.getDate();
  const month = months[now.getMonth()];
  const year = now.getFullYear();
  const time = now.toTimeString().split(' ')[0];
  return `${day} ${month} ${year} ${time}`;
};

